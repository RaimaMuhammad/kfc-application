export default function ProductImage({ src, alt, title, ...props }) {
  const handleError = (event) => {
    event.currentTarget.onerror = null;
    const exactImage = exactProductImages[title];
    if (exactImage) {
      event.currentTarget.src = exactImage;
    } else {
      event.currentTarget.style.visibility = "hidden";
    }
  };

  return (
    <img
      {...props}
      src={src || exactProductImages[title]}
      alt={alt || title || "Menu item"}
      title={title}
      onError={handleError}
    />
  );
}